def _slugify(name):
    """Convert college name to image filename slug."""
    import re
    name = name.lower()
    # Replace common words/patterns
    name = name.replace("indian institute of technology", "iit")
    name = name.replace("indian institute of management", "iim")
    name = name.replace("national institute of technology", "nit")
    name = name.replace("national institute of fashion technology", "nift")
    name = name.replace("national institute of design", "nid")
    name = name.replace("international institute of information technology", "iiit")
    name = name.replace("indian institute of science education and research", "iiser")
    name = name.replace("indian institute of science", "iisc")
    name = name.replace("all india institute of medical sciences", "aiims")
    name = name.replace("college of engineering", "coe")
    name = name.replace("institute of technology", "it")
    name = name.replace("university", "univ")
    # Remove special chars, collapse whitespace
    name = re.sub(r"[^a-z0-9\s]", "", name)
    name = re.sub(r"\s+", "_", name.strip())
    # Truncate to reasonable length
    if len(name) > 40:
        name = name[:40].rstrip("_")
    return name + ".jpg"


