def generate_college_database():
    """Generate college_database.csv"""
    headers = [
        "College_ID", "College_Name", "State", "District", "City",
        "College_Type", "Ownership", "Affiliated_University",
        "NAAC_Grade", "NIRF_Rank", "AICTE_Approved",
        "Hostel_Available", "Official_Website", "Admission_URL",
        "Notes", "Source"
    ]
    path = os.path.join(OUTPUT_DIR, "college_database.csv")
    with open(path, "w", newline="", encoding="utf-8-sig") as f:
        writer = csv.DictWriter(f, fieldnames=headers)
        writer.writeheader()
        for college in COLLEGES:
            # Validate controlled vocabularies
            assert college["Ownership"] in VALID_OWNERSHIP, f"Invalid Ownership: {college['Ownership']} for {college['College_ID']}"
            assert college["NAAC_Grade"] in VALID_NAAC, f"Invalid NAAC_Grade: {college['NAAC_Grade']} for {college['College_ID']}"
