def generate_college_course_mapping():
    """Generate college_course_mapping.csv"""
    headers = [
        "College_ID", "Course_Name", "Career_Domain", "Degree_Level",
        "Duration_Years", "Mode", "Eligibility_ID", "Source"
    ]
    path = os.path.join(OUTPUT_DIR, "college_course_mapping.csv")
    college_ids = {c["College_ID"] for c in COLLEGES}
    eligibility_ids = {e["Eligibility_ID"] for e in ELIGIBILITY_PROFILES}
    rows = []

    for college_id, courses in COLLEGE_COURSE_RULES.items():
        assert college_id in college_ids, f"Course mapping references unknown college: {college_id}"
        for course_name, career_domain, degree_level, duration, mode, elig_id in courses:
            assert career_domain in VALID_DOMAINS, f"Invalid domain: {career_domain}"
            assert elig_id in eligibility_ids, f"Invalid Eligibility_ID: {elig_id}"
            rows.append({
                "College_ID": college_id,
                "Course_Name": course_name,
                "Career_Domain": career_domain,
                "Degree_Level": degree_level,
                "Duration_Years": duration,
                "Mode": mode,
                "Eligibility_ID": elig_id,
                "Source": "Course offerings based on official college websites and NIRF program lists. Verify current offerings with institution.",
            })

    with open(path, "w", newline="", encoding="utf-8-sig") as f:
        writer = csv.DictWriter(f, fieldnames=headers)
        writer.writeheader()
        for row in rows:
            writer.writerow(row)

    # Dedup check
    seen = set()
    for row in rows:
        key = (row["College_ID"], row["Course_Name"])
        assert key not in seen, f"Duplicate mapping: {key}"
        seen.add(key)

    print(f"  college_course_mapping.csv: {len(rows)} mappings written to {path}")


